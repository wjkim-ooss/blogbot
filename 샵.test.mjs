// 제목으로키워드 — 발행 글이 어느 키워드 글인지 고르는 규칙.
// 조용히 틀리면 "키워드 0회"로 찍혀서 아무도 모른다. 그래서 여기서 못 박아 둔다.
import { test } from "node:test";
import assert from "node:assert";
import { 제목으로키워드, 한국날, 한국주 } from "./scripts/샵.mjs";

const 키워드들 = ["마곡 여드름관리", "마곡 좁쌀여드름", "마곡 피부관리"];

test("제목에 든 키워드를 고른다 — 띄어쓰기는 무시한다", () => {
  assert.equal(제목으로키워드(키워드들, "마곡피부관리 잘하는 곳"), "마곡 피부관리");
  assert.equal(제목으로키워드(키워드들, "마곡 피부관리 후기"), "마곡 피부관리");
});

test("겹치면 긴 쪽이 이긴다 — 좁은 키워드가 그 글의 주제다", () => {
  assert.equal(제목으로키워드(["마곡 여드름", "마곡 좁쌀여드름"], "마곡 좁쌀여드름 압출"), "마곡 좁쌀여드름");
});

test("자모 분리형(NFD) 제목도 같게 본다", () => {
  assert.equal(제목으로키워드(키워드들, "마곡 피부관리 후기".normalize("NFD")), "마곡 피부관리");
});

test("없으면 빈 문자열 — 검사를 껐다고 밝히려고", () => {
  assert.equal(제목으로키워드(키워드들, "전주 여드름 후기"), "");
  assert.equal(제목으로키워드(undefined, "아무 제목"), "");
  assert.equal(제목으로키워드(키워드들, undefined), "");
});

// 한국날 — "오늘 이미 쟀나"를 가르는 하루의 경계.
test("한국 시각으로 하루를 가른다 — 세계 표준시가 아니라", () => {
  // 09-20 23:30 KST 에 잰 것은 09-20 것이다 (세계 표준시로는 09-20T14:30Z 로 적힌다)
  assert.equal(한국날("2026-09-20T14:30:00.000Z"), "2026-09-20");
  // 09-21 00:30 KST 는 하루가 넘어간 것이다 (09-20T15:30Z)
  assert.equal(한국날("2026-09-20T15:30:00.000Z"), "2026-09-21");
});

test("아침 8시 예약이 어제 오후에 잰 것을 오늘 것으로 보지 않는다", () => {
  const 어제오후 = "2026-09-20T06:30:00.000Z";   // 09-20 15:30 KST
  const 오늘아침 = "2026-09-20T23:00:00.000Z";   // 09-21 08:00 KST
  assert.equal(한국날(어제오후) < 한국날(오늘아침), true);
  // 세계 표준시로 가르면 둘 다 09-20 이라 "오늘 이미 쟀다"가 되어 건너뛴다
  assert.equal(어제오후.slice(0, 10), 오늘아침.slice(0, 10));
});

test("잰 적 없는 키워드(0)는 아주 옛날로 쳐서 먼저 잰다", () => {
  assert.equal(한국날(0) < 한국날(), true);
  assert.equal(한국날("망가진 값"), "");   // 터지지 않는다 — 빈 값은 '안 잰 것'으로 본다
});

// 한국주 — "이번 주에 이미 쟀나"를 가르는 한 주의 경계. 월요일에 시작한다.
test("월요일에 한 주가 시작한다", () => {
  // 2026-09-21 은 월요일, 09-22 화요일, 09-27 일요일 — 넷 다 같은 주다
  assert.equal(한국주("2026-09-21T01:00:00.000Z"), "2026-09-21");
  assert.equal(한국주("2026-09-22T01:00:00.000Z"), "2026-09-21");
  assert.equal(한국주("2026-09-23T01:00:00.000Z"), "2026-09-21");
  assert.equal(한국주("2026-09-27T01:00:00.000Z"), "2026-09-21");
});

test("일요일과 그 다음 월요일은 다른 주다 — 월요일 예약이 다시 잰다", () => {
  assert.equal(한국주("2026-09-27T01:00:00.000Z") < 한국주("2026-09-28T01:00:00.000Z"), true);
});

test("한 주도 한국 시각으로 가른다", () => {
  // 09-21 00:30 KST(월요일)은 새 주다. 세계 표준시로는 아직 09-20 일요일이다.
  assert.equal(한국주("2026-09-20T15:30:00.000Z"), "2026-09-21");
  assert.equal(한국주("2026-09-20T14:30:00.000Z"), "2026-09-14");
});

test("잰 적 없는 키워드(0)는 아주 옛 주로 쳐서 먼저 잰다", () => {
  assert.equal(한국주(0) < 한국주(), true);
  assert.equal(한국주("망가진 값"), "");
});
