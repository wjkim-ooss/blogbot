// ---------- 채점 ----------
// 초안 하나를 잰다. 서버(고쳐쓰기 지시·저장)와 브라우저(검증 패널·목록 배지)가 모두 이것만 쓴다.
//
//   text        재는 대상 (사진 표시는 글자수에서 빠진다)
//   keyword     검증용 키워드
//   config      config.json 내용
//   목표글자수   원장이 직접 지정했으면 그 값, 아니면 0 → 최소글자수
//   ref         참고 레퍼런스 (사진 목표를 정한다)
//   title       따로 파싱해 둔 제목. 없으면 본문에서 뽑는다.
//   말투        "지시" | "요약"
//   유형        이 글을 누구 기준으로 볼 것인가 (초안 머리말에 적힌 값). 없으면 원장값의 유형.
// 한 문장은 한 줄에 끝까지 쓴다(2026-10-22 대표님, 두 사이트 공통). 문장이 끝나는 본문 줄의 비율로 잰다 —
// 낮으면 문장 중간에서 줄을 바꾼 것이다. 하한은 config.줄끝맺음.
const 끝맺는줄 = /([.?!]|[다요죠까]\??)\s*\S{0,2}$/;
export function 줄끝맺음재기(text, config) {
  const 설정 = config.줄끝맺음;
  if (!설정) return null;
  const 줄들 = 본문줄들(text);
  if (줄들.length < (설정.최소줄 ?? 20)) return null;
  const 끊긴 = 줄들.filter((l) => !끝맺는줄.test(l));
  return { 비율: Math.round(((줄들.length - 끊긴.length) / 줄들.length) * 100), 줄수: 줄들.length, 하한: 설정.하한, 끊긴 };
}

