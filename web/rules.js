// "한 줄에 1~3문장"으로 읽고 한 줄에 일곱 문장을 넣은 글이 나왔다(2026-10-23 점검 사이트 실서버).
// 소제목·자리 표시·해시태그·목록 줄은 그대로. 숫자 뒤 마침표(1.5배, "1. ")와 따옴표 안 문장 끝("…요?” 하고")에서는 끊지 않는다.
export function 문장줄나누기(body) {
  return String(body).split("\n").map((l) => {
    if (!다듬을줄(l.trim())) return l;
    const 들여 = l.match(/^\s*/)[0];
    return l.replace(/((?<!\d)[.?!]+)\s+(?=\S)/g, `$1\n${들여}`);
  }).join("\n");
}

