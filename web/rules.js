//   걱정풀기 = 글 전체에서 서로 다른 걱정 신호 몇 가지를 풀었나 × 가중치 (개수가 작아 비율로 안 잰다)
// 2026-09-14 우진: "실제 내 이야기가 들어갔는가, 공감 포인트, 고객이 걱정할 요소를 잘 풀었는가"까지.
const 세기 = (글, 말들) => (말들 || []).reduce((n, w) => n + (w ? 글.split(w).length - 1 : 0), 0);
export function 품질점수(text, config) {
  const Q = config.품질점수 || {};
  const 글 = text || "";
  const 자수 = noSpace(글) || 1;
  const 천자당 = (n) => (n / 자수) * 1000;
  const w = Q.가중치 || {};
  const 축 = {
    concrete: (글.match(new RegExp(Q.구체성패턴 || "$^", "g")) || []).length,
    story: 세기(글, Q.스토리텔링어),
    내이야기: 세기(글, Q.내이야기어),
    공감: 말투재기(본문만(글), config).공감,
    걱정풀기: 반박제거찾기(글, config).length,
    rebut: 세기(글, Q.반박제거어),
    abstract: 세기(글, 추상어목록(config)),
  };
  const score = Math.round(
    천자당(축.concrete) * (w.구체성 ?? 0) + 천자당(축.story) * (w.스토리텔링 ?? 0) + 천자당(축.내이야기) * (w.내이야기 ?? 0) +
    천자당(축.공감) * (w.공감 ?? 0) + 축.걱정풀기 * (w.걱정풀기 ?? 0) + 천자당(축.rebut) * (w.반박제거 ?? 0) +
    천자당(축.abstract) * (w.추상어 ?? 0)
  );
  return { score, ...축 };
}

// ---------- 글의 짜임 ----------
// 상위글이 어떻게 생겼나를 숫자로 잰다: 줄 나눔·문단·소제목·첫 줄·사진 간격, 그리고 초사고 글쓰기 기준
// (제목 방법·간접증명·예약 안내 자리). 문장은 넘기지 않는다 — 지시문에 문장을 넣으면 글마다 그 문장이 나온다.
// 크롤러가 수집 때 글마다 `짜임`으로 저장하고, 지시문은 짜임요약()으로 묶어 쓴다. 꼴은 config.짜임에 있다.
const 가운데 = (수들) => {
  const s = 수들.filter((n) => Number.isFinite(n)).sort((a, b) => a - b);
  return s.length ? s[Math.floor(s.length / 2)] : 0;
};
const 꼴캐시 = new Map();
const 꼴 = (s, f = "") => {
  if (!s) return null;
  const 키 = `${s}/${f}`;
  if (!꼴캐시.has(키)) 꼴캐시.set(키, new RegExp(s, f));
  return 꼴캐시.get(키);
};
const 질문끝 = /\?\s*\S{0,3}$/;
export function 글짜임({ title = "", text = "", images = 0 } = {}, config) {
  const Z = config.짜임 || {};
  const 잡음 = 꼴(Z.잡음줄), 소제목꼴 = 꼴(Z.소제목꼴), 최대 = Z.소제목최대글자 ?? 22;
  // 네이버 편집기 글을 긁으면 줄마다 사이에 빈 줄이 끼고, 글쓴이가 띄운 빈 줄은 보이지 않는 글자(​)만 든 줄로 온다.
  // 그런 줄이 있으면 그것만 문단 경계로 본다. 없는 글(다른 편집기)은 빈 줄이 경계다.
  const 원줄 = String(text).split("\n").filter((l) => !잡음?.test(l.trim()));
  const 보이지않는줄 = (l) => /[\u200B\u00A0]/.test(l) && !l.replace(/[\u200B\s]/g, "");
  const 경계 = 원줄.some(보이지않는줄) ? 보이지않는줄 : (l) => !l.trim();
  const 문단 = [];
  let 덩이 = [];
  for (const 날줄 of 원줄) {
    const l = 날줄.replace(/[\u200B\u00A0\t]/g, " ").trim();
    if (경계(날줄)) { if (덩이.length) { 문단.push(덩이); 덩이 = []; } }
    else if (l) 덩이.push(l);
  }
  if (덩이.length) 문단.push(덩이);
  const 글줄 = 문단.flat();
  const 소제목인가 = (l) => !!소제목꼴?.test(l) && noSpace(l) <= 최대;
  const 본줄 = 글줄.filter((l) => !소제목인가(l) && noSpace(l) >= 2);
  const 첫 = 본줄[0] || "";
  const 예약꼴 = 꼴(Z.예약꼴);
  const 예약자리 = 글줄.map((l, i) => (예약꼴?.test(l) ? i : -1)).filter((i) => i >= 0);
  const chars = noSpace(text);
  return {
    줄길이: 가운데(본줄.map(noSpace)),
    문단줄수: 가운데(문단.filter((d) => !d.every(소제목인가)).map((d) => d.length)), // 소제목만 든 덩이는 문단이 아니다
    문단수: 문단.length,
    소제목: 글줄.filter(소제목인가).length,
    질문비율: 본줄.length ? Math.round((본줄.filter((l) => 질문끝.test(l)).length / 본줄.length) * 100) : 0,
    사진간격: images ? Math.round(chars / images) : 0,
    후기: !!꼴(Z.후기꼴)?.test(title),
    초사고: {
      제목방법: Object.entries(Z.제목방법 || {}).filter(([, s]) => 꼴(s).test(title)).map(([이름]) => 이름),
      제목숫자: /\d/.test(title),
      첫줄: 꼴(Z.인사말)?.test(첫) ? "인사" : 질문끝.test(첫) ? "질문" : "장면·고민",
      간접증명: (String(text).match(꼴(Z.간접증명꼴 || "$^", "g")) || []).length,
      예약횟수: 예약자리.length,
      // 예약 안내가 글 끝 4분의 1 안에만 있으면 '끝에 한 번'이다
      예약끝에만: 예약자리.length > 0 && 예약자리.every((i) => i >= 글줄.length * 0.75),
    },
  };
}

// 상위글 묶음의 짜임을 한 벌로. 저장된 `짜임`이 없는 옛 글은 그 자리에서 잰다.
export function 짜임요약(posts, config) {
  const 것들 = (posts || []).map((p) => p.짜임 || 글짜임(p, config));
  if (!것들.length) return null;
  const 셈 = (f) => 것들.filter(f).length;
  const 제목방법 = {};
  for (const z of 것들) for (const m of z.초사고.제목방법) 제목방법[m] = (제목방법[m] || 0) + 1;
  const 소제목글 = 것들.filter((z) => z.소제목 > 0);
  return {
    편수: 것들.length,
    후기: 셈((z) => z.후기),
    줄길이: 가운데(것들.map((z) => z.줄길이)),
    문단줄수: 가운데(것들.map((z) => z.문단줄수)),
    문단수: 가운데(것들.map((z) => z.문단수)),
    소제목글: 소제목글.length,
    소제목: 가운데(소제목글.map((z) => z.소제목)),
    질문비율: 가운데(것들.map((z) => z.질문비율)),
    사진간격: 가운데(것들.map((z) => z.사진간격).filter(Boolean)),
    첫줄: { 인사: 셈((z) => z.초사고.첫줄 === "인사"), 질문: 셈((z) => z.초사고.첫줄 === "질문") },
    제목방법: Object.entries(config.짜임?.제목방법 || {}).map(([이름]) => [이름, 제목방법[이름] || 0]),
    제목숫자: 셈((z) => z.초사고.제목숫자),
    간접증명: 셈((z) => z.초사고.간접증명 > 0),
    예약끝에만: 셈((z) => z.초사고.예약끝에만),
    예약여러번: 셈((z) => z.초사고.예약횟수 > 1),
  };
}

// ---------- 영어 섞어 쓰기 ----------
// "진정 크림을 thick하게", "magnifier로 확인" — 소문자가 든 영어 낱말이 한글에 바로 붙은 꼴(config.영어섞임).
// 괄호 안 원어와 대문자 약어(BHA·PMID)는 괜찮다. 주소·해시태그 줄은 보지 않는다. 소제목과 사진 설명은 본다
// (실제로 소제목에 "thick하게", 사진 설명에 "피부 surface"가 들어갔다 — 사진 설명은 원장님이 보고 사진을 고르는 자리다).
const 영어낱말 = "(?<![A-Za-z])[A-Za-z]*[a-z][A-Za-z]{2,}";
const 영어붙음 = new RegExp(`${영어낱말}(?=[가-힣])`, "g"), 영어하나 = new RegExp(영어낱말, "g");
export function 영어섞임찾기(text, config) {
  if (!config.영어섞임) return [];
  const 허용 = (config.영어섞임.허용 || []).map((w) => w.toLowerCase());
  const 본 = stripPhotos(text || "").split("\n").filter((l) => !해시태그줄.test(l.trim()) && !/https?:|www\./.test(l)).join("\n").replace(/\([^)]*\)/g, " ");
  const 사진속 = ((text || "").match(사진표시) || []).join(" ");
  return [...new Set([...(본.match(영어붙음) || []), ...(사진속.match(영어하나) || [])])].filter((w) => !허용.includes(w.toLowerCase()));
}

// ---------- 쓰지 않기로 한 문장 ----------
// 우진이 못박은 문장 꼴(config.금지문구) — "방문 후 결정하셔도 늦지 않습니다", "피부과를 먼저 가 보세요".
// 문장(문장으로)마다 본다 — 줄로 보면 "결정하셔도\n늦지"를 놓친다.
// 항목마다 '검사' 스위치가 있다 — 그 유형에서 그 검사가 꺼져 있으면 걸지 않는다(정보 전달 글).
// 지시문(server.mjs)도 같은 함수로 고른다 — 보여 준 것과 잡는 것이 갈리지 않게.
export const 켜진금지문구 = (config, 검사설정) => (config.금지문구?.목록 || []).filter((x) => !x.검사 || 검사켜짐(검사설정, x.검사));
const 금지캐시 = new WeakMap();
const 금지식 = (x) => 금지캐시.get(x) ?? (금지캐시.set(x, new RegExp(x.꼴.join("|"))), 금지캐시.get(x));
export function 금지문구찾기(문장들, config, 검사설정) {
  const 걸린 = [];
  for (const x of 켜진금지문구(config, 검사설정)) {
    const re = 금지식(x);
    for (const 문장 of 문장들) if (re.test(문장)) 걸린.push({ 이름: x.이름, 문장, 대신: x.대신 || "" });
  }
  return 걸린;
}

// ---------- 가격 표기 ----------
// 금액이 박히는 순간 그 글은 가격 비교용으로만 소비된다.
// 출처검사와 겹쳐 보이지만 묻는 것이 다르다 — 저쪽은 "그 숫자 어디서 났나",
// 이쪽은 "원장이 준 값이라도 금액은 쓰지 마라"다.
// 금액 정규식을 따로 두지 않고 숫자꼴을 돌려쓴다 — 세 벌이 되면 반드시 갈라진다.
export function 가격찾기(text, config) {
  if (!config.가격금지) return [];
  return [...new Set([...(text || "").matchAll(숫자꼴)].filter((m) => m[2].endsWith("원")).map((m) => m[0].trim()))];
}

// ---------- 유사문서 ----------
// 네이버는 원본만 노출하고 베낀 글은 눌러 놓는다. 몇 %부터 걸리는지는 네이버가 밝힌 적이 없다
// — 떠도는 "70%"는 공식 수치가 아니다. 그래서 '얼마나 닮았나'를 추측하지 않고
// '남의 문장을 몇 어절이나 그대로 이어 썼나'를 센다. 그건 셀 수 있고, 고칠 자리도 짚어 준다.
//
// 재는 대상은 이 글에 딸린 레퍼런스다. AI에게 "이걸 참고해서 써라"라고 넘긴 바로 그 상위글이라,
// 베끼기가 일어난다면 거기서 일어난다. 원장이 손으로 옮겨 적은 것도 같은 자리에서 걸린다.
//
// 조각 크기와 문턱은 보관함 상위글 1,584쌍을 실제로 재서 정했다(config.유사문서.설명).
// 구두점을 지우고 어절만 뽑는다. 예전엔 정규식으로 두 번 훑고 split·filter까지 했는데,
// 편집기가 부르는 자리라 그것만으로 초안 1회 100µs를 썼다 — 한 번에 뽑으면 결과가 같고 절반이다.
const 어절나누기 = (t) => stripPhotos(t).match(/[\p{L}\p{N}]+/gu) || [];

// 레퍼런스 하나당 조각 지도를 한 번만 만든다 — 편집기가 글자마다 평가()를 부른다.
// 레퍼런스 객체는 키워드마다 캐시되어 같은 것이 돌아오므로 WeakMap이 실제로 맞는다.
const 조각색인 = new WeakMap();
function 조각지도(ref, n) {
  const 있던것 = 조각색인.get(ref);
  if (있던것?.n === n) return 있던것.지도;
  const 지도 = new Map();
  for (const p of ref.posts || []) {
    const 어절 = 어절나누기(p.text);
    for (let i = 0; i + n <= 어절.length; i++) {
      const 조각 = 어절.slice(i, i + n).join(" ");
      if (!지도.has(조각)) 지도.set(조각, p.title || ""); // 어느 글에서 왔는지 — 원장이 확인할 수 있게
    }
  }
  조각색인.set(ref, { n, 지도 });
  return 지도;
}

// 잰것: false면 "검사해서 깨끗함"이 아니라 "잴 대상이 없었음"이다. 불합격을 가르는
// 검사라 이 둘이 화면에서 같아 보이면 안 된다.
// 대조본은 하나(상위글 보관함)일 수도, 여럿(상위글 + 원장글 보관함)일 수도 있다.
// 보관함마다 조각 색인은 따로 둔다(편집기가 글자마다 불러도 색인을 다시 만들지 않게) —
// 글은 한 번만 쪼개고, 창마다 색인들을 차례로 본다.
export function 겹침찾기(text, refs, config) {
  const 설정 = config.유사문서;
  const 대조본 = [].concat(refs).filter((r) => r?.posts?.length);
  if (!설정 || !대조본.length) return { 잰것: false, 겹침률: 0, 최장: 0, 토막: [] };
  const n = 설정.조각어절;
  const 지도들 = 대조본.map((r) => 조각지도(r, n));
  const 어절 = 어절나누기(text);
  const 창수 = Math.max(0, 어절.length - n + 1);
  // 창마다 '어느 글에서 왔나'를 먼저 뽑아 두면, 이어진 구간을 훑는 일이 단순해진다
  const 출처찾기 = (조각) => { for (const 지도 of 지도들) { const 제목 = 지도.get(조각); if (제목 !== undefined) return 제목; } };
  const 출처들 = Array.from({ length: 창수 }, (_, i) => 출처찾기(어절.slice(i, i + n).join(" ")));
  // 이어진 겹침은 길이와 무관하게 다 적어 둔다. 짧은 겹침이 여기저기 흩어져
  // 겹침률만 오르는 글도 있는데, 문턱 넘는 것만 적으면 짚어 줄 대목이 없어 조용해진다.
  const 토막 = [];
  for (let i = 0; i < 창수; i++) {
    if (출처들[i] === undefined) continue;
    const 시작 = i;
    while (i + 1 < 창수 && 출처들[i + 1] !== undefined) i += 1;
    토막.push({ 말: 어절.slice(시작, i + n).join(" "), 어절수: i + n - 시작, 출처: 출처들[시작] });
  }
  토막.sort((a, b) => b.어절수 - a.어절수); // 이 정렬이 아래 '최장 = 토막[0]' 등식을 떠받친다
  return {
    잰것: true,
    겹침률: 창수 ? Number(((출처들.filter((x) => x !== undefined).length / 창수) * 100).toFixed(1)) : 0,
    최장: 토막[0]?.어절수 || 0,
    토막: 토막.slice(0, 설정.보여줄개수),
  };
}

// ---------- 제목의 약속 ----------
// 제목에 "3가지"라고 써 놓고 본문이 두 항목뿐이면, 읽는 사람은 하나를 못 찾고 나간다.
// 이건 기계가 셀 수 있다 — 제목의 수와 소제목(###) 수를 맞춰 본다.
const 제목수 = /(\d+)\s*(?:가지|개|곳|단계|이유|가지고|까지)/;
export function 약속숫자(제목, text) {
  const m = (제목 || "").match(제목수);
  if (!m) return null;
  const 약속 = Number(m[1]);
  if (!약속 || 약속 > 12) return null; // 연차·분·원 같은 수는 항목 약속이 아니다
  // 번호 붙은 소제목(### 1. …)이 있으면 그게 항목이다. 들어가는 말·샵 소개 같은 번호 없는 소제목까지 세면
  // "3가지" 글에 번호 소제목 셋 + 다른 소제목 다섯을 8개로 잡아 멀쩡한 글을 불합격시켰다(2026-10-07).
  const 번호소제목 = ((text || "").match(/^#{2,4}\s+(?:\d+\s*[.)]|[①-⑫])\s*\S/gm) || []).length;
  if (번호소제목) return { 약속, 항목: 번호소제목, 말: m[0] };
  const 소제목 = ((text || "").match(/^#{2,4}\s+\S.*$/gm) || []).length;
  const 번호줄 = ((text || "").match(/^\s*(?:\d+[.)]|[①-⑫])\s*\S/gm) || []).length;
  const 차례말 = ((text || "").match(/(?:^|\n)\s*(?:첫째|둘째|셋째|넷째|다섯째|첫 번째|두 번째|세 번째|네 번째|다섯 번째|이유 ?\d)/g) || []).length;
  return { 약속, 항목: Math.max(소제목, 번호줄, 차례말), 말: m[0] };
}

