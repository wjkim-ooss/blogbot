// 낱말 목록 하나를 정규식 하나로 굳혀 둔다. 낱말마다 본문을 훑으면 글자 하나 칠 때마다
// 수십 번 훑게 된다 — 편집기가 평가()를 키 입력마다 부른다.
const 문구캐시 = new WeakMap();
const 정규식몫 = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
function 문구정규식(목록) {
  if (!목록?.length) return null;
  let 것 = 문구캐시.get(목록);
  if (!것) {
    const 본 = 목록.map(정규식몫).join("|");
    것 = { 하나: new RegExp(본), 모두: new RegExp(본, "g") };
    문구캐시.set(목록, 것);
  }
  return 것;
}
const 문구뽑기 = (text, 목록) => {
  const re = 문구정규식(목록);
  return re ? [...new Set(text.match(re.모두) || [])] : [];
};

const 쉼표 = /[,，、]/;
const 쉼표나누기 = /[,，、]\s*/;
const 문단경계 = /\n\s*\n/;

// ---------- 문장 길이 ----------
// 모바일에서 읽힌다는 전제로만 잰다. 억지로 끊으면 어색해지므로
// 불합격이 아니라 권장이다 — 상한을 넘는 문장이 몇 %인지로 본다.
// 세는 단위는 '독자가 한 호흡에 읽는 토막'이다 — 줄바꿈으로 이미 나뉘어 오고,
// 쉼표끊기가 켜져 있으면 쉼표 앞뒤도 따로 센다 (우진: 점이나 반점으로 끊어도 된다).
export const 문장길이범위 = (config) => `${config.문장길이?.하한}~${config.문장길이?.상한}자`;

export function 긴문장(본문들, config) {
  const { 상한 = 0, 하한 = 0, 쉼표끊기 } = config.문장길이 || {};
  // 쉼표가 없는 문장은 쪼갤 것도 없다 — 대부분이 그렇다(상한이 20자다)
  const 토막들 = 쉼표끊기
    ? 본문들.flatMap((s) => (쉼표.test(s) ? s.split(쉼표나누기).map((x) => x.trim()).filter(Boolean) : [s]))
    : 본문들;
  let 합 = 0, 최대 = -1, 가장긴 = null, 짧은수 = 0;
  const 긴것 = [];
  for (const 문장 of 토막들) {
    const 길이 = noSpace(문장);
    합 += 길이;
    if (상한 && 길이 > 상한) 긴것.push(문장);
    if (하한 && 길이 < 하한) 짧은수 += 1;
    if (길이 > 최대) { 최대 = 길이; 가장긴 = 문장; }
  }
  const 전체 = 토막들.length;
  const 몫 = (n) => (전체 ? Math.round((n / 전체) * 100) : 0);
  // 짧은비율: 하한에 못 미치는 토막이 몇 %인가. 다 짧으면 그것도 뚝뚝 끊긴 글이다.
  return { 전체, 긴것, 가장긴, 비율: 몫(긴것.length), 짧은비율: 몫(짧은수), 평균: 전체 ? Math.round(합 / 전체) : 0 };
}

// ---------- 말투 배합 ----------
// 딱딱하기만 하면 말을 거는 느낌이 사라지고, 부드럽기만 하면 전문성이 흐려진다.
// 공감 어미를 몇 %나 섞었는지 세고, 원장이 책임지는 문장이 부드러운 어미로 흐르지 않았는지 본다.
// "회원권은 권하지 않아요"는 약속이 가볍다. 같은 말이라도 "권하지 않습니다"여야 박힌다.
//
// 어미로 판정하므로 문장 끝의 마침표·물음표·따옴표는 걷어내고 본다.
// 예전에는 이 자르기가 some() 콜백 안에 있어 문장 하나마다 17번씩 다시 돌았다
// — 편집기가 글자마다 부르는 함수라 그것만으로 평가()가 2.2배 느려졌다.
const 어미꼬리 = /[\s"'”’)\]~.!?…]+$/;
const 한숫자반복 = /^(\d)\1+$/;
// 말을 거는 것(~시죠? ~인데요 ~거든요)과 가벼워지는 것(~어요 ~해요 ~네요)은 다르다.
// 앞은 원장이 고객 쪽을 한 번 보는 것이고, 뒤는 글 전체가 가벼워지는 것이라 따로 센다.
// 비율이 기준 안이어도 ~입니다가 대여섯 문장씩 줄지어 서면 안내문처럼 읽힌다 —
// 제일 길게 이어진 줄(연속단정)과 그 첫 문장(연속자리)도 같이 돌려준다.
export function 말투재기(본문들, config, 범위 = null) {
  const { 공감어미 = [], 약속신호 = [], 부드러운어미 = [], 단정어미 = [], 기본비율,
    연속허용 = Infinity, 같은어미상한 = Infinity } = config.말투 || {};
  let 공감 = 0, 연속 = 0, 연속단정 = 0, 연속자리 = "", 줄시작 = "";
  const 약속흐림 = [], 부드러운문장 = [], 어미별 = {};
  for (const 문장 of 본문들) {
    const 끝 = 문장.replace(어미꼬리, "");
    const 건어미 = 공감어미.find((e) => 끝.endsWith(e));
    if (건어미) { 공감 += 1; 어미별[건어미] = (어미별[건어미] || 0) + 1; }
    const 부드러움 = 부드러운어미.some((e) => 끝.endsWith(e));
    if (부드러움) 부드러운문장.push(문장);
    if (부드러움 && 약속신호.some((w) => 문장.includes(w))) 약속흐림.push(문장);
    // 말 거는 어미(~하셨을 겁니다)는 ~니다로 끝나도 단정 줄짓기에 넣지 않는다 — 지시문이 그것으로 줄짓기를 끊으라고 한다
    if (!건어미 && 단정어미.some((e) => 끝.endsWith(e))) {
      if (연속 === 0) 줄시작 = 문장;
      연속 += 1;
      if (연속 > 연속단정) { 연속단정 = 연속; 연속자리 = 줄시작; }
    } else 연속 = 0;
  }
  const [최소, 최대] = 범위 || 기본비율 || [0, 100];
  const 백분율 = (n) => (본문들.length ? Math.round((n / 본문들.length) * 100) : 0);
  return {
    전체: 본문들.length, 공감, 비율: 백분율(공감), 최소, 최대, 약속흐림,
    부드러운문장, 부드러움비율: 백분율(부드러운문장.length),
    연속단정, 연속자리, 연속허용, 같은어미상한,
    // 한 어미만 되풀이되면 리듬이 아니라 버릇이다 — 상한을 넘긴 어미와 횟수
    반복어미: Object.entries(어미별).filter(([, n]) => n > 같은어미상한).map(([e, n]) => ({ 어미: e, 횟수: n })),
  };
}

